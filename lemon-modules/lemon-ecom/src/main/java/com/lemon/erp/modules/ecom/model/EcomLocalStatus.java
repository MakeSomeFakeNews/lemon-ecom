package com.lemon.erp.modules.ecom.model;

/**
 * 订单处理状态（字典 ecom_local_status）：本系统内的处理进度。
 * <p>
 * 作业流程（自发货）：待审核 →（审单规则 / 人工审核，按发货仓可用库存检查）→ 待打单（已生成包裹）/ 缺货 →（包裹申请运单号）→ 待发货
 * →（包裹扫描发货：生成销售出库并回传平台）→ 已发货；拆分为多个包裹、只发了一部分时为部分发货。审核前后都可挂起（拦截），取消挂起回到挂起前的状态。
 * <p>
 * 直接出库（平台配送订单、不走包裹的简单情况）：待审核 → 已出库（生成销售出库）→ 已发货（填写物流并回传平台）。
 * 取消 / 退款的订单为已关闭，SKU 未匹配等为异常
 */
public enum EcomLocalStatus {
    /** 待审核（原「待处理」）：导入 / 同步后还没有审核 */
    PENDING,
    /** 已挂起：审单规则要求人工审核或人工拦截，取消挂起后回到挂起前的状态 */
    ON_HOLD,
    /** 异常：SKU 未匹配本地物料、出库失败等，处理后可重新审核 / 出库 */
    EXCEPTION,
    /** 缺货：审核时发货仓可用库存不足，补货后「重新检查库存」 */
    OUT_OF_STOCK,
    /** 待打单：审核通过，已生成包裹，等待申请运单号 */
    AUDITED,
    /** 待发货：包裹都已有运单号（面单），等待扫描发货 */
    LABELED,
    /** 已出库：直接出库（不经过包裹）生成了销售出库，等待填写物流 */
    OUTBOUND,
    /** 部分发货：拆分的包裹只发出了一部分 */
    PARTIAL,
    /** 已发货 */
    SHIPPED,
    /** 已关闭 */
    CLOSED
}
